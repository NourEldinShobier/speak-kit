// Generates the SpeakKit "Voice hub" logo for the apps: assets/logo/{logo,logo-flat,logo-small}.svg and src/logo-data.ts.
// The geometry comes from the design master, designs/logo/final/logo.mjs, so the app icons match the approved logo.
// Run: node scripts/gen-logo.mjs   (needs designs/logo/v2/node_modules for the shape kit)
import { mkdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { COLORS, SIZES, colour, geometry } from "../../../../designs/logo/final/logo.mjs";

const OUT = new URL("../assets/logo/", import.meta.url);
const f1 = (v) => (Math.round(v * 10) / 10).toString();
const full = geometry(SIZES.full),
  small = geometry(SIZES.small);
const files = { logo: colour(full), "logo-flat": colour(full, { withShadow: false }), "logo-small": colour(small, { withShadow: false }) };

// Compact path for the bundled data: a 512 grid (error under 1/1024 of the mark, 0.07 px at 72 px), relative
// commands, no separators before minus signs. Handles the M, C, L and Z commands the generator emits.
const compact = (d) => {
  let out = "",
    px = 0,
    py = 0,
    sx = 0,
    sy = 0,
    last = "";
  const nums = (vs) => vs.reduce((acc, v) => acc + (acc && v >= 0 ? " " : "") + v, "");
  for (const [, cmd, args] of d.matchAll(/([MCLZ])([^MCLZ]*)/g)) {
    const n = (args.match(/-?[0-9]+\.?[0-9]*/g) ?? []).map((v) => Math.round(+v / 2)); // 512 grid: half-pixel steps of the 1024 canvas
    if (cmd === "Z") {
      out += "z";
      px = sx;
      py = sy;
      last = "z";
      continue;
    }
    if (cmd === "M") {
      out += "M" + nums(n);
      px = sx = n[0];
      py = sy = n[1];
      last = "M";
      continue;
    }
    const step = cmd === "C" ? 6 : 2,
      rel = [];
    for (let i = 0; i < n.length; i += step) {
      for (let j = 0; j < step; j += 2) rel.push(n[i + j] - px, n[i + j + 1] - py);
      px = n[i + step - 2];
      py = n[i + step - 1];
    }
    out += (last === cmd ? " " : cmd.toLowerCase()) + nums(rel);
    last = cmd;
  }
  return out;
};
const fills = [COLORS.sky, COLORS.yellow, COLORS.violet, COLORS.deep];
// The hub circle on the 512 grid, and every third point of the master's 121-point wave (bundle size; invisible at icon sizes).
const hub = (r) => `M${256 - r / 2} 256a${r / 2} ${r / 2} 0 1 0 ${r} 0a${r / 2} ${r / 2} 0 1 0 ${-r} 0Z`;
const wave = (d) =>
  `M${d
    .slice(1)
    .split("L")
    .filter((_, i) => i % 3 === 0)
    .join("L")}`;
const variant = (g, p) =>
  `{ clip: ${JSON.stringify(compact(g.clip))}, pieces: ${JSON.stringify(g.pieces.map(compact))}, hub: ${JSON.stringify(hub(p.r))}, wave: ${JSON.stringify(compact(wave(g.waveStroke)))}, waveWidth: ${f1(g.sw / 2)} }`;
/** The text of src/logo-data.ts (tests/generated.test.ts compares it with the committed file). */
export const renderLogoData = () =>
  `// Generated by scripts/gen-logo.mjs from the Voice hub logo geometry. Do not edit.\nexport interface LogoVariant { clip: string; pieces: string[]; hub: string; wave: string; waveWidth: number }\nexport const LOGO_COLORS = { pieces: ${JSON.stringify(fills)}, hub: "${COLORS.hub}", wave: "${COLORS.wave}" } as const;\nexport const LOGO_FULL: LogoVariant = ${variant(full, SIZES.full)};\nexport const LOGO_SMALL: LogoVariant = ${variant(small, SIZES.small)};\n`;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(OUT, { recursive: true });
  for (const [n, svg] of Object.entries(files)) writeFileSync(new URL(`${n}.svg`, OUT), svg);
  writeFileSync(new URL("../src/logo-data.ts", import.meta.url), renderLogoData());
  console.log("logo written", Object.keys(files).join(", "));
}
