// Generates src/main/icon-data.ts: the app icon (256 px) and one 32 px tray icon per state, as base64 PNGs.
// Run after changing the logo (packages/ui: node scripts/gen-logo.mjs): node scripts/make-icons.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { logoPng, BADGES } from "./icons-lib.mjs";

const b64 = (size, state) => JSON.stringify(logoPng(size, state).toString("base64"));
const states = ["normal", "asleep", ...Object.keys(BADGES)];
const body = `// Generated by scripts/make-icons.mjs from the Voice hub logo. Do not edit.
import type { TrayState } from "../shared/engine-view";
export const APP_ICON_PNG = ${b64(256)};
export const TRAY_ICON_PNG: Record<TrayState, string> = {
${states.map((s) => `  ${s}: ${b64(32, s)},`).join("\n")}
};
`;
writeFileSync(fileURLToPath(new URL("../src/main/icon-data.ts", import.meta.url)), body);
console.log("icon-data.ts written:", states.join(", "));
